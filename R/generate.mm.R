                "imputomics", "pcaMethods", "LLS", "SVDimpute", "BPCA", "PPCA", "DreamAI", "limma",
                "prolfqua", "proDA", "BH", "fdrtool", "clusterProfiler", "GSEA", "aPEAR"),
        package = c("DEprot", "DEprot", NA, "MBQN", "HarmonizR", NA, "missForest", "VIM",
                    NA, "pcaMethods", NA, NA, NA, NA, NA, "limma",
                    "prolfqua", "proDA", NA, "fdrtool", "clusterProfiler", NA, "aPEAR"),
        citation = c(
          "Eickhoff N., Hoekman L., Bleijerveld O., Bergman A.M., Zwart W., Gregoricchio S. DEprot: a comprehensive R-package for the analyses of label-free quantitation mass-spectrometry data. NAR Genomics and Bioinformatics 8(1), 2026. doi: 10.1093/nargab/lqag015",
