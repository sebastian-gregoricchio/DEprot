#' @title generate.mm
#'
#' @description Drafts the Material-and-Methods paragraph describing the analyses stored in a
#' \code{DEprot} or \code{DEprot.analyses} object. All the steps that left a trace in the object are
#' described in the order in which they were applied (normalization or batch correction,
#' bottom-distribution randomization, imputation, differential analyses and, when the corresponding
#' object is provided, geneset enrichment), together with the parameters that affect the results and
#' would be needed to reproduce them. Tools are cited with numbers in the text and the reference list
#' is printed underneath.
#'
#' The paragraph is a draft: the numbers and the parameters are read from the object, but the wording
#' is expected to be adapted to the study and to the style of the journal. Steps that happen upstream
#' of \code{DEprot} (sample preparation, LC-MS/MS acquisition, database search) are not stored in the
#' object; the search engine can be mentioned through \code{quantification.software}, everything else
#' must be added by hand.
#'
#' @param DEprot.object An object of class \code{DEprot} or \code{DEprot.analyses}.
#' @param enrichment.object An object of class \code{DEprot.enrichResult}, as generated by \link{geneset.enrichment}, to describe the enrichment analyses as well. Default: \code{NULL} (no enrichment paragraph).
#' @param quantification.software String naming the software used to generate the protein intensities, version included (e.g., \code{"MaxQuant (v2.4.2)"}). Default: \code{NULL}, in which case the sentence is left generic.
#' @param quantification.reference String with the citation of \code{quantification.software}. When provided, it is cited in the text and becomes the first entry of the reference list. Default: \code{NULL}.
#' @param geneset.database String naming the geneset collection used for the enrichment (e.g., \code{"CORUM v5.0"}, \code{"MSigDB Hallmark"}). Ignored when \code{enrichment.object} is \code{NULL}. Default: \code{NULL}.
#' @param geneset.reference String with the citation of \code{geneset.database}. Default: \code{NULL}.
#' @param contrasts Numeric vector indicating which contrasts should be described. Default: \code{NULL} (all the contrasts available in the object).
#' @param include.results.summary Logical value defining whether the number of differential proteins per contrast should be reported. Default: \code{TRUE}.
#' @param include.package.versions Logical value defining whether the version of the packages installed in the current session should be appended to the corresponding references. Default: \code{TRUE}.
#' @param extra.references String vector of citations to append, unnumbered in the text, at the end of the reference list. Default: \code{NULL}.
#' @param add.headers Logical value defining whether the 'Material and Methods' and 'References' headers should be added. Default: \code{TRUE}.
#' @param wrap.width Numeric value indicating the number of characters per line used to wrap the text. Set to \code{NULL} to keep each paragraph on a single line (useful when pasting into a word processor). Default: \code{100}.
#' @param output.file String with the path of a text file in which the result should be written. Default: \code{NULL} (no file written).
#' @param verbose Logical value defining whether the text should be printed in the console. Default: \code{TRUE}.
#'
#' @return Invisibly, a list containing:
#'      \describe{
#'        \item{\code{text}: }{string with the numbered Material-and-Methods paragraphs}
#'        \item{\code{references}: }{data.frame with the number, the key and the citation of each reference}
#'        \item{\code{parameters}: }{data.frame collecting the parameters mentioned in the text}
#'        \item{\code{full.text}: }{string combining text and reference list, as printed and as written in \code{output.file}}}
#'
#' @seealso \link{export.report}, \link{impute.counts}, \link{diff.analyses}, \link{geneset.enrichment}
#'
#' @author Sebastian Gregoricchio
#'
#' @examples
#' # Draft for a differential analysis
#' mm <- generate.mm(DEprot.object = DEprot::test.toolbox$diff.exp.limma)
#'
#' # Same, mentioning the search engine and writing the text to a file
#' \dontrun{
#' mm <- generate.mm(DEprot.object = DEprot::test.toolbox$diff.exp.limma,
#'                   quantification.software = "MaxQuant (v2.4.2)",
#'                   quantification.reference = paste0("Cox J., Mann M. MaxQuant enables high peptide ",
#'                                                     "identification rates. Nature Biotechnology 26, ",
#'                                                     "1367-1372, 2008. doi: 10.1038/nbt.1511"),
#'                   output.file = "material.and.methods.txt")
#' }
#'
#' @importFrom utils packageVersion
#'
#' @export generate.mm


generate.mm =
  function(DEprot.object,
           enrichment.object = NULL,
           quantification.software = NULL,
           quantification.reference = NULL,
           geneset.database = NULL,
           geneset.reference = NULL,
           contrasts = NULL,
           include.results.summary = TRUE,
           include.package.versions = TRUE,
           extra.references = NULL,
           add.headers = TRUE,
           wrap.width = 100,
           output.file = NULL,
           verbose = TRUE) {

    ### check object
    if (!any(c("DEprot", "DEprot.analyses") %in% class(DEprot.object))) {
      stop("The input must be an object of class 'DEprot' or 'DEprot.analyses'.")
    }

    if (!is.null(enrichment.object)) {
      if (!("DEprot.enrichResult" %in% class(enrichment.object))) {
        stop("The 'enrichment.object' must be an object of class 'DEprot.enrichResult'.")
      }
    }



    #############################################################################################
    ### Bibliography
    #############################################################################################

