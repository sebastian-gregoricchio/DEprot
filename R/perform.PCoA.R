#' @title .lingoes.correction
#' @description Internal. Applies the Lingoes (1971) correction to a \code{dist} object, i.e.
#' \code{d_prime = sqrt(d^2 + 2*c)} for \code{i != j}, where \code{c} is the absolute value of the most
#' negative eigenvalue of the Gower-centered matrix. This makes the dissimilarities euclidean-embeddable.
#' @param d An object of class \code{dist}.
#' @return An object of class \code{dist}.
#' @importFrom stats as.dist
#' @keywords internal

.lingoes.correction =
  function(d) {
    n = attr(d, "Size")
    D = as.matrix(d)

    ## Gower double-centering: G = -0.5 * J %*% D^2 %*% J
    J = diag(n) - matrix(1/n, nrow = n, ncol = n)
    G = -0.5 * (J %*% (D^2) %*% J)

    ev = eigen((G + t(G))/2, symmetric = TRUE, only.values = TRUE)$values
    c1 = min(ev)

    if (c1 >= 0) {return(d)}  # already euclidean, nothing to correct

    D.corrected = sqrt(D^2 + 2*abs(c1))
    diag(D.corrected) = 0

    return(stats::as.dist(D.corrected))
  }



#' @title .PCoA.axis.loadings
#' @description Internal. Computes the a-posteriori projection of the proteins onto the principal
#' coordinates, as the correlation between each protein profile and each axis.
#' @param DEprot.object An object of class \code{DEprot} or \code{DEprot.analyses}.
#' @param which.data String indicating the count type to use.
#' @param coordinates data.frame of the principal coordinates (samples as rows).
#' @param verbose Logical value indicating whether messages should be printed.
#' @return A data.frame of protein-vs-axis correlations.
#' @importFrom stats cor
#' @keywords internal

.PCoA.axis.loadings =
  function(DEprot.object,
           which.data,
           coordinates,
           verbose = TRUE) {

    if (!("DEprot" %in% class(DEprot.object)) & !("DEprot.analyses" %in% class(DEprot.object))) {
      warning("The 'DEprot.object' provided is not of class 'DEprot'. The protein projections will not be computed.")
      return(NULL)
    }

    ### Extract the counts
    if (tolower(which.data) == "raw") {
      mat = DEprot.object@raw.counts
    } else if (tolower(which.data) %in% c("norm", "normalized", "normal")) {
      mat = DEprot.object@norm.counts
    } else if (tolower(which.data) %in% c("imputed", "imp", "impute")) {
      mat = DEprot.object@imputed.counts
    } else if (tolower(which.data) %in% c("randomized", "random")) {
      mat = DEprot.object@random.counts
    } else {
      mat = NULL
    }

    if (is.null(mat)) {
      warning(paste0("Counts of type '", which.data, "' are not available in the 'DEprot.object'. ",
                     "The protein projections will not be computed."))
      return(NULL)
    }

    ### Match the samples used in the ordination
    samples = rownames(coordinates)

    if (!all(samples %in% colnames(mat))) {
      warning(paste0("Some of the samples used in the correlation are not available in the 'DEprot.object' counts. ",
                     "The protein projections will not be computed."))
      return(NULL)
    }

    mat = mat[, samples, drop = FALSE]

    ### Convert to log2 (same behavior of perform.PCA)
    if (!is.numeric(DEprot.object@log.base)) {
      if (verbose == TRUE) {
        message("The log.base is not numeric, linear counts are assumed. Counts will be converted to log2(score+1) values to compute the protein projections.")
      }
      mat = log2(mat + 1)
    } else if (as.numeric(DEprot.object@log.base) != 2) {
      if (verbose == TRUE) {
        message("The log.base is not 2, counts will be converted to log2 values to compute the protein projections.")
      }
      mat = log2(DEprot.object@log.base^mat)
    }

    mat[is.nan(mat)] = NA

    ### Remove non-informative proteins (constant or fully missing)
    protein.sd = apply(mat, 1, stats::sd, na.rm = TRUE)
    keep = !is.na(protein.sd) & protein.sd > 0
    mat = mat[keep, , drop = FALSE]

    if (nrow(mat) == 0) {
      warning("No protein with a non-zero variance is available. The protein projections will not be computed.")
      return(NULL)
    }

    ### Correlate each protein profile with each axis
    loadings = suppressWarnings(stats::cor(x = t(mat),
                                           y = as.matrix(coordinates),
                                           use = "pairwise.complete.obs"))

    loadings.df = data.frame(protein = rownames(loadings),
                             data.frame(loadings),
                             row.names = NULL)

    return(loadings.df)
  }
