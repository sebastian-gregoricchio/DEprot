#' @title plot.sPLSDA.cumulative
#'
#' @description Plots the proportion of protein variance carried by each component of a sPLS-DA, with the cumulative curve on top.
#'
#' @param DEprot.sPLSDA.object An object of class \code{DEprot.sPLSDA}.
#' @param bar.color String indicating the color to use for the bar fill. Default: \code{"steelblue"}.
#' @param line.color String indicating the color to use for the line and the dots of the cumulative curve. Default: \code{"navyblue"}.
#' @param title String indicating the title of the plot (markdown annotation supported). Default: \code{NULL}.
#'
#' @details
#' A sPLS-DA component is built to separate the classes, not to capture variance, and it only sees the handful of proteins retained by \code{keepX}. The percentages are therefore much lower than the ones of a PCA computed on the same data, and comparing the two is meaningless: what this plot shows is how the (little) variance used by the model is spread over the components.
#'
#' @return A ggplot object.
#'
#' @seealso \link{perform.sPLSDA}, \link{plot.PC.cumulative}
#'
#' @name plot.sPLSDA.cumulative
#'
#' @import ggplot2
#' @import ggtext
#'
#' @author Sebastian Gregoricchio
#'
#' @examples
#' splsda <- perform.sPLSDA(DEprot.object = DEprot::test.toolbox$dpo.imp,
#'                          group.column = "condition",
#'                          keepX = 5,
#'                          validate = FALSE)
#'
#' plot.sPLSDA.cumulative(DEprot.sPLSDA.object = splsda)
#'
#' @export plot.sPLSDA.cumulative

plot.sPLSDA.cumulative =
  function(DEprot.sPLSDA.object,
           bar.color = "steelblue",
           line.color = "navyblue",
           title = NULL) {

    ### check object
    if (!("DEprot.sPLSDA" %in% class(DEprot.sPLSDA.object))) {
      stop("The input must be an object of class 'DEprot.sPLSDA'.")
    }

    ### harmonized access to the ordination slots
    ord = .ordination.slots(DEprot.sPLSDA.object)


    ### Generate the plot (shared body with the PCA and PCoA cumulative plots)
    cumulative.plot =
      .cumulative.plot(importance = ord$importance,
                       axis.prefix = ord$axis.prefix,
                       axis.title = ord$axis.title,
                       bar.color = bar.color,
                       line.color = line.color,
                       title = title,
                       broken.stick = FALSE,
                       filter.positive = FALSE)

    return(cumulative.plot)
  } # END function




