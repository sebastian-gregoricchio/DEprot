#' @title .splsda.group.colors
#'
#' @description
#' Internal. Checks the colors provided for the classes and completes them when they are missing or too few.
#'
#' @param group.colors Named (or unnamed) color vector, or \code{NULL}.
#' @param group.labels Character vector of the class names.
#'
#' @return A named color vector.
#'
#' @importFrom grDevices rainbow
#'
#' @keywords internal

.splsda.group.colors =
  function(group.colors,
           group.labels) {

    if (is.null(group.colors) | length(group.colors) < length(group.labels)) {
      if (!is.null(group.colors)) {
        message("The number of colors provided is lower than the number of classes (",
                length(group.labels), "). Values will be assigned automatically.")
      }
      group.colors = grDevices::rainbow(n = length(group.labels), s = 0.5)
    }

    if (is.null(names(group.colors))) {
      names(group.colors) = group.labels
    }

    return(group.colors)
  } # END function




