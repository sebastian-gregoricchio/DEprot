#' @title plot.sPLSDA.stability
#'
#' @description Plots how often each protein was re-selected across the cross-validation folds of a sPLS-DA.
#'
#' @param DEprot.sPLSDA.object An object of class \code{DEprot.sPLSDA}.
#' @param component Numeric value indicating the component to display. Default: \code{1}.
#' @param n.proteins Numeric value indicating the maximum number of proteins to display. Default: \code{25}.
#' @param bar.color String indicating the color of the bars of the proteins retained in the final model. Default: \code{"steelblue"}.
#' @param other.color String indicating the color of the bars of the proteins that were not retained in the final model. Default: \code{"gray70"}.
#' @param frequency.threshold Numeric value (0-1) drawn as a dashed line, used as a visual reference for a stable selection. Default: \code{0.8}.
#' @param protein.names.pattern String indicating a pattern to be passed to gsub and removed from the protein names. Default: \code{NULL} (no changes).
#' @param axes.text.size Numeric value indicating the font size of the axis text. Default: \code{9}.
#' @param title String indicating the title of the plot (markdown annotation supported). Default: \code{NULL} (automatic title).
#'
#' @details
#' The list of proteins returned by a sparse model is much less stable than it looks: on a small design, resampling the samples is often enough to swap half of it. A protein re-selected in nearly every fold is a marker worth following up; one appearing in a third of them is a property of the particular split, and the number written next to the bars is the only way to tell the two apart.
#'
#' Proteins that were not retained in the final model but were frequently selected during the resampling are shown as well, since they are exactly the candidates that a slightly different dataset would have picked.
#'
#' @return A ggplot object.
#'
#' @seealso \link{perform.sPLSDA}, \link{plot.sPLSDA.loadings}
#'
#' @name plot.sPLSDA.stability
#'
#' @import ggplot2
#' @import ggtext
#'
#' @author Sebastian Gregoricchio
#'
#' @examples
#' \donttest{
#' # the performances are estimated by resampling the samples
#' splsda <- perform.sPLSDA(DEprot.object = DEprot::test.toolbox$dpo.imp,
#'                          group.column = "condition",
#'                          keepX = 5,
#'                          validate = TRUE,
#'                          folds = 3,
#'                          nrepeat = 1)
#'
#' plot.sPLSDA.stability(DEprot.sPLSDA.object = splsda, component = 1)
#' }
#'
#' @export plot.sPLSDA.stability

plot.sPLSDA.stability =
  function(DEprot.sPLSDA.object,
           component = 1,
           n.proteins = 25,
           bar.color = "steelblue",
           other.color = "gray70",
           frequency.threshold = 0.8,
           protein.names.pattern = NULL,
           axes.text.size = 9,
           title = NULL) {

    ### check object
    if (!("DEprot.sPLSDA" %in% class(DEprot.sPLSDA.object))) {
      stop("The input must be an object of class 'DEprot.sPLSDA'.")
    }

    if (is.null(DEprot.sPLSDA.object@performance)) {
      stop("This object does not contain any performance estimation: re-run `perform.sPLSDA` with 'validate = TRUE'.")
    }

    stability = DEprot.sPLSDA.object@performance$stability

    if (is.null(stability)) {
      stop("The selection frequencies are not available in this object.")
    }

    tb = stability[stability$component == component, , drop = FALSE]

    if (nrow(tb) == 0) {
      stop("No selection frequency is available for the component ", component, ".")
    }


    ### Flag the proteins retained in the final model
    retained = DEprot.sPLSDA.object@selected.proteins[[component]]
    tb$retained = ifelse(tb$prot.id %in% retained,
                         yes = "Retained in the final model",
                         no = "Not retained")

    tb = tb[order(-tb$frequency), , drop = FALSE]

    if (!is.null(n.proteins)) {
      tb = utils::head(tb, round(n.proteins, 0))
    }

    if (!is.null(protein.names.pattern)) {
      tb$prot.id = gsub(protein.names.pattern, "", tb$prot.id)
    }

    tb$prot.id = factor(tb$prot.id, levels = rev(unique(tb$prot.id)))

    fill.colors = c("Retained in the final model" = bar.color,
                    "Not retained" = other.color)

    if (is.null(title)) {
      title = paste0("**Selection stability, component ", component, "**")
    }


    ### Generate the plot
    stability.plot =
      ggplot(data = tb,
             aes(x = frequency,
                 y = prot.id,
                 fill = factor(retained, levels = names(fill.colors)))) +
      geom_bar(stat = "identity", width = 0.75) +
      geom_vline(xintercept = frequency.threshold, color = "firebrick", linetype = 2) +
      scale_fill_manual(values = fill.colors, name = NULL, drop = FALSE) +
      scale_x_continuous(limits = c(0, 1), expand = c(0, 0)) +
      xlab("Frequency of selection across the folds") +
      ylab(NULL) +
      ggtitle(label = title,
              subtitle = paste0("*", DEprot.sPLSDA.object@parameters$validation,
                                "; dashed red line: ", frequency.threshold * 100, "% of the folds*")) +
      theme_classic() +
      theme(axis.line.y = element_blank(),
            axis.ticks.y = element_blank(),
            axis.text = element_text(color = "black", size = axes.text.size),
            panel.grid.major.x = element_line(color = "gray", linewidth = 0.1),
            plot.title = ggtext::element_markdown(hjust = 0.5),
            plot.subtitle = ggtext::element_markdown(hjust = 0.5, size = 8))

    return(stability.plot)
  } # END function




