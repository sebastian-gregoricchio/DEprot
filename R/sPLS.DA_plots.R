#' @title plot.sPLSDA.scatter.123
#'
#' @description Combines the component1-vs-component2 and component3-vs-component2 scatters of a sPLS-DA.
#'
#' @param DEprot.sPLSDA.object An object of class \code{DEprot.sPLSDA}.
#' @param color.column String indicating the name of the column in the metadata to use as factor for the dot colors. Default: \code{NULL} (the column used to fit the model).
#' @param shape.column String indicating the name of the column in the metadata to use as factor for the dot shapes. Default: \code{NULL} (all dots).
#' @param label.column String indicating the name of the column in the metadata to use as label of the dots. Default: \code{NULL} (no labeling).
#' @param dot.colors Color-vector to use for the points. Default: \code{NULL} (automatic colors).
#' @param ellipse Logical value indicating whether a confidence ellipse should be drawn around each group. Default: \code{TRUE}.
#' @param ellipse.level Numeric value (0-1) indicating the confidence level of the ellipses. Default: \code{0.95}.
#' @param title String indicating the title of the combined plot (markdown annotation supported). Default: \code{NULL}.
#'
#' @return A patchwork object.
#'
#' @seealso \link{perform.sPLSDA}, \link{plot.sPLSDA.scatter}
#'
#' @name plot.sPLSDA.scatter.123
#'
#' @import ggplot2
#' @import ggtext
#' @import patchwork
#'
#' @author Sebastian Gregoricchio
#'
#' @examples
#' splsda <- perform.sPLSDA(DEprot.object = DEprot::test.toolbox$dpo.imp,
#'                          group.column = "condition",
#'                          keepX = 5,
#'                          validate = FALSE)
#'
#' plot.sPLSDA.scatter.123(DEprot.sPLSDA.object = splsda,
#'                         shape.column = "replicate")
#'
#' @export plot.sPLSDA.scatter.123

plot.sPLSDA.scatter.123 =
  function(DEprot.sPLSDA.object,
           color.column = NULL,
           shape.column = NULL,
           label.column = NULL,
           dot.colors = NULL,
           ellipse = TRUE,
           ellipse.level = 0.95,
           title = NULL) {

    ### check object
    if (!("DEprot.sPLSDA" %in% class(DEprot.sPLSDA.object))) {
      stop("The input must be an object of class 'DEprot.sPLSDA'.")
    }

    if (is.null(color.column)) {color.column = DEprot.sPLSDA.object@group.column}

    if (DEprot.sPLSDA.object@parameters$ncomp < 3) {
      stop("At least 3 components are required to generate the combined scatter, but the model has ",
           DEprot.sPLSDA.object@parameters$ncomp, ".")
    }


    ### Define the colors
    coordinates = DEprot.sPLSDA.object@components

    if (is.factor(coordinates[, color.column])) {
      color.labels = levels(droplevels(coordinates[, color.column]))
    } else {
      color.labels = unique(coordinates[, color.column])
    }

    scatter.colors = .splsda.group.colors(group.colors = dot.colors, group.labels = color.labels)


    ### Generate the two panels
    plot.1.2 =
      plot.sPLSDA.scatter(DEprot.sPLSDA.object = DEprot.sPLSDA.object,
                          comp.x = 1,
                          comp.y = 2,
                          color.column = color.column,
                          shape.column = shape.column,
                          label.column = label.column,
                          ellipse = ellipse,
                          ellipse.level = ellipse.level) +
      scale_color_manual(values = scatter.colors) +
      theme(legend.position = "none")

    plot.3.2 =
      plot.sPLSDA.scatter(DEprot.sPLSDA.object = DEprot.sPLSDA.object,
                          comp.x = 3,
                          comp.y = 2,
                          color.column = color.column,
                          shape.column = shape.column,
                          label.column = label.column,
                          ellipse = ellipse,
                          ellipse.level = ellipse.level) +
      ylab(NULL) +
      scale_color_manual(values = scatter.colors)


    ### Export the combined plot
    if (is.null(title)) {
      return(patchwork::wrap_plots(plot.1.2, plot.3.2, nrow = 1))
    } else {
      return(patchwork::wrap_plots(plot.1.2, plot.3.2, nrow = 1) +
               patchwork::plot_annotation(title = title,
                                          theme = theme(plot.title = ggtext::element_markdown(hjust = 0.5))))
    }
  } # END function




