#' @title plot.sPLSDA.loadings
#'
#' @description Plots the loadings of the proteins retained on a component of a sPLS-DA, colored by the class in which each of them is the highest.
#'
#' @param DEprot.sPLSDA.object An object of class \code{DEprot.sPLSDA}.
#' @param component Numeric value indicating the component to display. Default: \code{1}.
#' @param n.proteins Numeric value indicating the maximum number of proteins to display, ranked by absolute loading. Default: \code{25}.
#' @param group.colors Color-vector (optionally named on the classes) used for the bars. Default: \code{NULL} (automatic colors).
#' @param protein.names.pattern String indicating a pattern to be passed to gsub and removed from the protein names. Default: \code{NULL} (no changes).
#' @param bar.width Numeric value indicating the width of the bars. Default: \code{0.75}.
#' @param axes.text.size Numeric value indicating the font size of the axis text. Default: \code{9}.
#' @param title String indicating the title of the plot (markdown annotation supported). Default: \code{NULL} (automatic title).
#'
#' @details
#' The sign of a loading is only interpretable once the orientation of the component is fixed, which \link{perform.sPLSDA} does through the \code{reference.group} argument: a positive coefficient marks a protein pulling the samples towards that group. The color adds the information the coefficient alone does not carry, namely in which class the protein is actually the most abundant, assigned by the highest median as done by \code{mixOmics::plotLoadings}.
#'
#' @return A ggplot object.
#'
#' @seealso \link{perform.sPLSDA}, \link{plot.sPLSDA.stability}, \link{get.sPLSDA.results}
#'
#' @name plot.sPLSDA.loadings
#'
#' @import ggplot2
#' @import ggtext
#'
#' @author Sebastian Gregoricchio
#'
#' @examples
#' splsda <- perform.sPLSDA(DEprot.object = DEprot::test.toolbox$dpo.imp,
#'                          group.column = "condition",
#'                          keepX = 5,
#'                          validate = FALSE)
#'
#' plot.sPLSDA.loadings(DEprot.sPLSDA.object = splsda,
#'                      component = 1,
#'                      n.proteins = 5)
#'
#' @export plot.sPLSDA.loadings

plot.sPLSDA.loadings =
  function(DEprot.sPLSDA.object,
           component = 1,
           n.proteins = 25,
           group.colors = NULL,
           protein.names.pattern = NULL,
           bar.width = 0.75,
           axes.text.size = 9,
           title = NULL) {

    ### check object
    if (!("DEprot.sPLSDA" %in% class(DEprot.sPLSDA.object))) {
      stop("The input must be an object of class 'DEprot.sPLSDA'.")
    }

    available = sort(unique(DEprot.sPLSDA.object@loadings$component))

    if (!(component %in% available)) {
      stop("The component ", component, " is not available.\n",
           "       Available components: ", paste(available, collapse = ", "))
    }


    ### Collect the selected proteins
    tb = DEprot.sPLSDA.object@loadings
    tb = tb[tb$component == component & tb$selected %in% TRUE, , drop = FALSE]

    if (nrow(tb) == 0) {
      stop("No protein was selected on the component ", component, ": there is nothing to plot.")
    }

    tb = tb[order(-tb$abs.loading), , drop = FALSE]

    if (!is.null(n.proteins)) {
      tb = utils::head(tb, round(n.proteins, 0))
    }

    if (!is.null(protein.names.pattern)) {
      tb$prot.id = gsub(protein.names.pattern, "", tb$prot.id)
    }

    ## the bars are sorted by the value of the loading, so that the two directions of the
    ## component sit on the two sides of the zero line
    tb = tb[order(tb$loading), , drop = FALSE]
    tb$prot.id = factor(tb$prot.id, levels = unique(tb$prot.id))


    ### Colors of the classes
    group.labels = DEprot.sPLSDA.object@parameters$groups
    bar.colors = .splsda.group.colors(group.colors = group.colors, group.labels = group.labels)

    if (is.null(title)) {
      title = paste0("**Component ", component, "** (", nrow(tb), " of ",
                     length(DEprot.sPLSDA.object@selected.proteins[[component]]), " selected proteins)")
    }


    ### Generate the plot
    loadings.plot =
      ggplot(data = tb,
             aes(x = loading,
                 y = prot.id,
                 fill = factor(contrib.group, levels = group.labels))) +
      geom_vline(xintercept = 0, color = "gray", linetype = 2) +
      geom_bar(stat = "identity", width = bar.width) +
      scale_fill_manual(values = bar.colors,
                        name = DEprot.sPLSDA.object@group.column,
                        drop = FALSE) +
      xlab("Loading") +
      ylab(NULL) +
      ggtitle(label = title,
              subtitle = paste0("*positive: towards ", DEprot.sPLSDA.object@parameters$reference.group, "*")) +
      theme_classic() +
      theme(axis.line.y = element_blank(),
            axis.ticks.y = element_blank(),
            axis.text = element_text(color = "black", size = axes.text.size),
            panel.background = element_blank(),
            panel.grid.major.x = element_line(color = "gray", linewidth = 0.1),
            plot.title = ggtext::element_markdown(hjust = 0.5),
            plot.subtitle = ggtext::element_markdown(hjust = 0.5, size = 8))

    return(loadings.plot)
  } # END function




