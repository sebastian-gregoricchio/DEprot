#' @title .splsda.axis.labels
#'
#' @description
#' Internal. Builds the axis titles of the sPLS-DA scatters. The generic ordination label ('comp1 (12.3%)') is replaced by an explicit one, since on a supervised model the percentage refers to the protein block and not to the separation between the classes.
#'
#' @param importance importance table of the \code{DEprot.sPLSDA} object.
#' @param axis Number of the component.
#'
#' @return A string.
#'
#' @keywords internal

.splsda.axis.labels =
  function(importance,
           axis) {

    percentage = importance$Percentage.of.Variance[axis]

    if (is.na(percentage)) {
      return(paste0("Component ", axis))
    }

    return(paste0("Component ", axis, " (", round(percentage, 1), "% of the protein variance)"))
  } # END function




