#' @title plot.sPLSDA.biplot
#'
#' @description Overlays the loadings of the selected proteins on the scatter of two components of a sPLS-DA.
#'
#' @param DEprot.sPLSDA.object An object of class \code{DEprot.sPLSDA}.
#' @param comp.x Number indicating which component to display on the x-axis. Default: \code{1}.
#' @param comp.y Number indicating which component to display on the y-axis. Default: \code{2}.
#' @param color.column String indicating the name of the column in the metadata to use as factor for the dot colors. Default: \code{NULL} (the column used to fit the model).
#' @param shape.column String indicating the name of the column in the metadata to use as factor for the dot shapes. Default: \code{NULL} (all dots).
#' @param label.column String indicating the name of the column in the metadata to use as label of the dots. Default: \code{NULL} (no labeling).
#' @param ellipse Logical value indicating whether a confidence ellipse should be drawn around each group. Default: \code{FALSE}.
#' @param ellipse.level Numeric value (0-1) indicating the confidence level of the ellipses. Default: \code{0.95}.
#' @param plot.zero.line.x Logical value to indicate whether to plot a gray dashed line in correspondence of x=0. Default: \code{TRUE}.
#' @param plot.zero.line.y Logical value to indicate whether to plot a gray dashed line in correspondence of y=0. Default: \code{TRUE}.
#' @param n.loadings Number of proteins to display, ranked by their distance from the origin in the plane displayed. Default: \code{10}.
#' @param loading.color String indicating the color of the arrows and of their labels. Default: \code{"turquoise4"}.
#' @param loading.arrow.size Numeric value indicating the linewidth of the arrows. Default: \code{0.6}.
#' @param loading.label.size Numeric value indicating the font size of the labels. Default: \code{3}.
#' @param loading.alpha Numeric value (0-1) indicating the transparency of arrows and labels. Default: \code{0.7}.
#' @param loading.scale Numeric multiplier to manually adjust the length of the arrows. Default: \code{0.8}.
#'
#' @details
#' Only the proteins retained on at least one of the two components displayed can appear: a protein dropped by the sparsity penalty has a coefficient of exactly zero and no direction to point to.
#'
#' @return A ggplot object.
#'
#' @seealso \link{perform.sPLSDA}, \link{plot.sPLSDA.scatter}, \link{plot.sPLSDA.loadings}
#'
#' @name plot.sPLSDA.biplot
#'
#' @import ggplot2
#' @import ggrepel
#'
#' @author Sebastian Gregoricchio
#'
#' @examples
#' splsda <- perform.sPLSDA(DEprot.object = DEprot::test.toolbox$dpo.imp,
#'                          group.column = "condition",
#'                          keepX = 5,
#'                          validate = FALSE)
#'
#' plot.sPLSDA.biplot(DEprot.sPLSDA.object = splsda,
#'                    comp.x = 1,
#'                    comp.y = 2,
#'                    n.loadings = 5)
#'
#' @export plot.sPLSDA.biplot

plot.sPLSDA.biplot =
  function(DEprot.sPLSDA.object,
           comp.x = 1,
           comp.y = 2,
           color.column = NULL,
           shape.column = NULL,
           label.column = NULL,
           ellipse = FALSE,
           ellipse.level = 0.95,
           plot.zero.line.x = TRUE,
           plot.zero.line.y = TRUE,
           n.loadings = 10,
           loading.color = "turquoise4",
           loading.arrow.size = 0.6,
           loading.label.size = 3,
           loading.alpha = 0.7,
           loading.scale = 0.8) {

    ### check object
    if (!("DEprot.sPLSDA" %in% class(DEprot.sPLSDA.object))) {
      stop("The input must be an object of class 'DEprot.sPLSDA'.")
    }

    if (is.null(color.column)) {color.column = DEprot.sPLSDA.object@group.column}

    ord = .ordination.slots(DEprot.sPLSDA.object)


    ### Build the loadings table for the plane displayed
    loadings = DEprot.sPLSDA.object@loadings

    available = sort(unique(loadings$component))

    if (!(comp.x %in% available) | !(comp.y %in% available)) {
      stop("The components requested (", comp.x, ", ", comp.y, ") are not available.\n",
           "       Available components: ", paste(available, collapse = ", "))
    }

    loading.x = loadings[loadings$component == comp.x, c("prot.id", "loading")]
    loading.y = loadings[loadings$component == comp.y, c("prot.id", "loading")]

    colnames(loading.x)[2] = "loading.x"
    colnames(loading.y)[2] = "loading.y"

    loadings.df = merge(loading.x, loading.y, by = "prot.id")
    colnames(loadings.df)[1] = "variable"

    ## a protein dropped on both components sits exactly on the origin and would only add
    ## an arrow of length zero
    loadings.df = loadings.df[loadings.df$loading.x != 0 | loadings.df$loading.y != 0, , drop = FALSE]

    if (nrow(loadings.df) == 0) {
      stop("No protein was selected on the components ", comp.x, " and ", comp.y, ": the biplot is empty.")
    }


    ### Rank and rescale the loadings (shared with the PCA and PCoA biplots)
    scaled = .scale.loadings(loadings.df = loadings.df,
                             scores.x = ord$coordinates[, paste0("comp", comp.x)],
                             scores.y = ord$coordinates[, paste0("comp", comp.y)],
                             n.loadings = n.loadings,
                             loading.scale = loading.scale)


    ### Build the biplot (the arrows are inserted below the points)
    biplot =
      .ordination.scatter(coordinates = ord$coordinates,
                          importance = ord$importance,
                          axis.prefix = ord$axis.prefix,
                          axis.x = comp.x,
                          axis.y = comp.y,
                          color.column = color.column,
                          shape.column = shape.column,
                          label.column = label.column,
                          plot.zero.line.x = plot.zero.line.x,
                          plot.zero.line.y = plot.zero.line.y,
                          positive.axis = ord$positive.axis,
                          extra.layers = .loading.layers(loadings.top = scaled$top,
                                                         loading.color = loading.color,
                                                         loading.arrow.size = loading.arrow.size,
                                                         loading.label.size = loading.label.size,
                                                         loading.alpha = loading.alpha))

    if (ellipse == TRUE) {
      biplot =
        biplot +
        stat_ellipse(mapping = aes(group = color),
                     type = "norm",
                     level = ellipse.level,
                     linetype = 2,
                     linewidth = 0.4,
                     show.legend = FALSE)
    }

    biplot =
      biplot +
      xlab(.splsda.axis.labels(importance = ord$importance, axis = comp.x)) +
      ylab(.splsda.axis.labels(importance = ord$importance, axis = comp.y))

    return(biplot)
  } # END function




