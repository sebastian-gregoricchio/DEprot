#' @title plot.sPLSDA.tuning
#'
#' @description Plots the classification error obtained over the grid of \code{keepX} values tested during the tuning of a sPLS-DA, and marks the value retained on each component.
#'
#' @param DEprot.sPLSDA.object An object of class \code{DEprot.sPLSDA}.
#' @param component Numeric value (or vector) indicating the component(s) to display. Default: \code{NULL} (all the components).
#' @param line.colors Color-vector used for the components. Default: \code{NULL} (automatic colors).
#' @param show.sd Logical value indicating whether the standard deviation over the repeats should be drawn as a ribbon. Default: \code{TRUE}.
#' @param title String indicating the title of the plot (markdown annotation supported). Default: \code{"**Tuning of keepX**"}.
#'
#' @details
#' The curves are usually flat over a wide range of values: many different numbers of proteins classify the samples equally well, and the minimum picked by the tuning is one point of a plateau rather than an optimum. Reading the plot is worth the time, because a value sitting at the left edge of that plateau gives a shorter and more interpretable protein list at no cost in error rate.
#'
#' @return A ggplot object.
#'
#' @seealso \link{perform.sPLSDA}, \link{plot.sPLSDA.performance}
#'
#' @name plot.sPLSDA.tuning
#'
#' @import ggplot2
#' @import ggtext
#'
#' @author Sebastian Gregoricchio
#'
#' @examples
#' \donttest{
#' # the tuning runs only when 'keepX' is left to NULL
#' splsda <- perform.sPLSDA(DEprot.object = DEprot::test.toolbox$dpo.imp,
#'                          group.column = "condition",
#'                          test.keepX = c(5, 10, 20),
#'                          validate = FALSE,
#'                          folds = 3,
#'                          nrepeat = 1)
#'
#' plot.sPLSDA.tuning(DEprot.sPLSDA.object = splsda)
#' }
#'
#' @export plot.sPLSDA.tuning

plot.sPLSDA.tuning =
  function(DEprot.sPLSDA.object,
           component = NULL,
           line.colors = NULL,
           show.sd = TRUE,
           title = "**Tuning of keepX**") {

    ### check object
    if (!("DEprot.sPLSDA" %in% class(DEprot.sPLSDA.object))) {
      stop("The input must be an object of class 'DEprot.sPLSDA'.")
    }

    if (is.null(DEprot.sPLSDA.object@tuning)) {
      stop("This object does not contain any tuning: the 'keepX' was provided at the `perform.sPLSDA` call.")
    }


    tb = DEprot.sPLSDA.object@tuning$error.rate

    if (!is.null(component)) {
      missing.components = setdiff(component, unique(tb$component))

      if (length(missing.components) > 0) {
        stop("The component(s) ", paste(missing.components, collapse = ", "), " are not available in the tuning.")
      }

      tb = tb[tb$component %in% component, , drop = FALSE]
    }

    tb$component.label = factor(paste0("comp", tb$component),
                                levels = paste0("comp", sort(unique(tb$component))))


    ### Values retained on each component
    choice = DEprot.sPLSDA.object@tuning$choice.keepX

    choice.tb =
      data.frame(component = seq_along(choice),
                 keepX = as.numeric(choice),
                 stringsAsFactors = FALSE)

    choice.tb = choice.tb[choice.tb$component %in% unique(tb$component), , drop = FALSE]
    choice.tb = merge(choice.tb, tb[, c("component", "keepX", "error.rate")], by = c("component", "keepX"))
    choice.tb$component.label = factor(paste0("comp", choice.tb$component), levels = levels(tb$component.label))


    ### Colors
    component.colors = .splsda.group.colors(group.colors = line.colors,
                                            group.labels = levels(tb$component.label))


    ### Generate the plot
    tuning.plot =
      ggplot(data = tb,
             aes(x = keepX,
                 y = error.rate,
                 color = component.label,
                 fill = component.label))

    if (show.sd == TRUE & !all(is.na(tb$error.rate.sd))) {
      tuning.plot =
        tuning.plot +
        geom_ribbon(aes(ymin = error.rate - error.rate.sd,
                        ymax = error.rate + error.rate.sd),
                    alpha = 0.15,
                    color = NA)
    }

    tuning.plot =
      tuning.plot +
      geom_line(linewidth = 0.6) +
      geom_point(size = 1.5, stroke = NA) +
      geom_point(data = choice.tb,
                 mapping = aes(x = keepX, y = error.rate),
                 shape = 21,
                 size = 3.5,
                 stroke = 1,
                 fill = NA,
                 color = "black",
                 inherit.aes = FALSE) +
      scale_x_log10(breaks = sort(unique(tb$keepX))) +
      scale_color_manual(values = component.colors, name = NULL) +
      scale_fill_manual(values = component.colors, name = NULL) +
      xlab("Number of proteins retained (keepX)") +
      ylab("Classification error rate") +
      ggtitle(label = title,
              subtitle = paste0("*circled: value retained (", DEprot.sPLSDA.object@parameters$dist, ", ",
                                DEprot.sPLSDA.object@parameters$validation, ")*")) +
      theme_classic() +
      theme(axis.text = element_text(color = "black"),
            axis.text.x = element_text(angle = 45, hjust = 1),
            panel.grid.major.y = element_line(color = "gray", linewidth = 0.1),
            plot.title = ggtext::element_markdown(hjust = 0.5),
            plot.subtitle = ggtext::element_markdown(hjust = 0.5, size = 8),
            aspect.ratio = 0.6)

    return(tuning.plot)
  } # END function




