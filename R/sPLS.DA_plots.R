#' @title plot.sPLSDA.performance
#'
#' @description Plots the cross-validated classification error of a sPLS-DA as a function of the number of components.
#'
#' @param DEprot.sPLSDA.object An object of class \code{DEprot.sPLSDA}.
#' @param metric String indicating which error to display. One among: 'both', 'overall', 'BER' (balanced error rate). Default: \code{"both"}.
#' @param distance String indicating the prediction distance(s) to display. One among: 'all', 'max.dist', 'centroids.dist', 'mahalanobis.dist'. Default: \code{"all"}.
#' @param line.colors Color-vector used for the distances. Default: \code{NULL} (automatic colors).
#' @param title String indicating the title of the plot (markdown annotation supported). Default: \code{"**Cross-validated classification error**"}.
#'
#' @details
#' The balanced error rate is the average of the error rates of each class, and it is the value to read on an unbalanced design: with 9 samples in one group and 3 in the other, a model that assigns everything to the larger group already reaches an overall error of 25%.
#'
#' The dashed gray line marks the error of a random assignment, that is one minus the frequency of the largest class. A model sitting on that line is not discriminating anything, however clean its scatter plot looks.
#'
#' @return A ggplot object.
#'
#' @seealso \link{perform.sPLSDA}, \link{plot.sPLSDA.tuning}, \link{plot.sPLSDA.auroc}
#'
#' @name plot.sPLSDA.performance
#'
#' @import ggplot2
#' @import ggtext
#'
#' @author Sebastian Gregoricchio
#'
#' @examples
#' \donttest{
#' # the performances are estimated by resampling the samples
#' splsda <- perform.sPLSDA(DEprot.object = DEprot::test.toolbox$dpo.imp,
#'                          group.column = "condition",
#'                          keepX = 5,
#'                          validate = TRUE,
#'                          folds = 3,
#'                          nrepeat = 1)
#'
#' plot.sPLSDA.performance(DEprot.sPLSDA.object = splsda)
#' }
#'
#' @export plot.sPLSDA.performance

plot.sPLSDA.performance =
  function(DEprot.sPLSDA.object,
           metric = "both",
           distance = "all",
           line.colors = NULL,
           title = "**Cross-validated classification error**") {

    ### check object
    if (!("DEprot.sPLSDA" %in% class(DEprot.sPLSDA.object))) {
      stop("The input must be an object of class 'DEprot.sPLSDA'.")
    }

    if (is.null(DEprot.sPLSDA.object@performance)) {
      stop("This object does not contain any performance estimation: re-run `perform.sPLSDA` with 'validate = TRUE'.")
    }

    tb = DEprot.sPLSDA.object@performance$error.rate

    if (is.null(tb)) {
      stop("The error rates are not available in this object.")
    }


    ### Subset the metric
    if (tolower(metric) %in% c("overall")) {
      tb = tb[tb$metric == "Overall error rate", , drop = FALSE]
    } else if (tolower(metric) %in% c("ber", "balanced")) {
      tb = tb[tb$metric == "Balanced error rate", , drop = FALSE]
    } else if (!(tolower(metric) %in% c("both", "all"))) {
      stop("The 'metric' must be one among: 'both', 'overall', 'BER'.")
    }


    ### Subset the distance
    if (!(tolower(distance) %in% c("all", "both"))) {
      if (!(distance %in% unique(tb$distance))) {
        stop("The 'distance' requested is not available.\n",
             "       Available distances: ", paste(unique(tb$distance), collapse = ", "))
      }
      tb = tb[tb$distance == distance, , drop = FALSE]
    }

    tb$metric = factor(tb$metric, levels = c("Overall error rate", "Balanced error rate"))


    ### Error of a random assignment, used as reference
    group.sizes = table(DEprot.sPLSDA.object@groups)
    random.error = 1 - (max(group.sizes) / sum(group.sizes))


    ### Colors
    distance.colors = .splsda.group.colors(group.colors = line.colors,
                                           group.labels = sort(unique(tb$distance)))


    ### Generate the plot
    performance.plot =
      ggplot(data = tb,
             aes(x = component,
                 y = error.rate,
                 color = distance)) +
      geom_hline(yintercept = random.error, color = "gray", linetype = 2) +
      geom_line(linewidth = 0.6) +
      geom_point(size = 2, stroke = NA) +
      facet_wrap(facets = ~metric, nrow = 1) +
      scale_x_continuous(breaks = sort(unique(tb$component))) +
      scale_color_manual(values = distance.colors, name = "Distance") +
      xlab("Number of components") +
      ylab("Error rate") +
      ggtitle(label = title,
              subtitle = paste0("*", DEprot.sPLSDA.object@parameters$validation,
                                ifelse(DEprot.sPLSDA.object@parameters$validation == "Mfold",
                                       yes = paste0(" (", DEprot.sPLSDA.object@parameters$folds, " folds, ",
                                                    DEprot.sPLSDA.object@parameters$nrepeat, " repeats)"),
                                       no = ""),
                                "; dashed gray line: error of a random assignment*")) +
      theme_classic() +
      theme(axis.text = element_text(color = "black"),
            strip.background = element_blank(),
            strip.text = element_text(color = "black", face = "bold"),
            panel.grid.major.y = element_line(color = "gray", linewidth = 0.1),
            plot.title = ggtext::element_markdown(hjust = 0.5),
            plot.subtitle = ggtext::element_markdown(hjust = 0.5, size = 8),
            aspect.ratio = 0.8)

    return(performance.plot)
  } # END function




