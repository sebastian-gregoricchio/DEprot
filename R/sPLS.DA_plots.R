#' @title plot.sPLSDA.auroc
#'
#' @description Plots the cross-validated area under the ROC curve (AUC) of each class against all the others, component by component.
#'
#' @param DEprot.sPLSDA.object An object of class \code{DEprot.sPLSDA}.
#' @param component Numeric value (or vector) indicating the component(s) to display. Default: \code{NULL} (all the components).
#' @param point.colors Color-vector used for the components. Default: \code{NULL} (automatic colors).
#' @param show.sd Logical value indicating whether the standard deviation over the repeats should be drawn as an error bar. Default: \code{TRUE}.
#' @param title String indicating the title of the plot (markdown annotation supported). Default: \code{"**Cross-validated AUC**"}.
#'
#' @details
#' This is the AUC computed by \code{mixOmics::perf} over the resampling, and not a ROC curve drawn on the samples used to fit the model: the latter would be optimistic by construction, since a supervised model is fitted precisely to rank those samples correctly. The dashed line at 0.5 is the value of a coin toss.
#'
#' The comparisons are one class against all the others pooled, which is how mixOmics reports them for a multi-class design.
#'
#' @return A ggplot object.
#'
#' @seealso \link{perform.sPLSDA}, \link{plot.sPLSDA.performance}
#'
#' @name plot.sPLSDA.auroc
#'
#' @import ggplot2
#' @import ggtext
#'
#' @author Sebastian Gregoricchio
#'
#' @examples
#' \donttest{
#' # the performances are estimated by resampling the samples
#' splsda <- perform.sPLSDA(DEprot.object = DEprot::test.toolbox$dpo.imp,
#'                          group.column = "condition",
#'                          keepX = 5,
#'                          validate = TRUE,
#'                          folds = 3,
#'                          nrepeat = 1)
#'
#' plot.sPLSDA.auroc(DEprot.sPLSDA.object = splsda)
#' }
#'
#' @export plot.sPLSDA.auroc

plot.sPLSDA.auroc =
  function(DEprot.sPLSDA.object,
           component = NULL,
           point.colors = NULL,
           show.sd = TRUE,
           title = "**Cross-validated AUC**") {

    ### check object
    if (!("DEprot.sPLSDA" %in% class(DEprot.sPLSDA.object))) {
      stop("The input must be an object of class 'DEprot.sPLSDA'.")
    }

    if (is.null(DEprot.sPLSDA.object@performance)) {
      stop("This object does not contain any performance estimation: re-run `perform.sPLSDA` with 'validate = TRUE'.")
    }

    tb = DEprot.sPLSDA.object@performance$auc

    if (is.null(tb)) {
      stop("The AUC values are not available in this object.")
    }

    if (!is.null(component)) {
      missing.components = setdiff(component, unique(tb$component))

      if (length(missing.components) > 0) {
        stop("The component(s) ", paste(missing.components, collapse = ", "), " are not available.")
      }

      tb = tb[tb$component %in% component, , drop = FALSE]
    }

    tb$component.label = factor(paste0("comp", tb$component),
                                levels = paste0("comp", sort(unique(tb$component))))

    component.colors = .splsda.group.colors(group.colors = point.colors,
                                            group.labels = levels(tb$component.label))


    ### Generate the plot
    auroc.plot =
      ggplot(data = tb,
             aes(x = AUC,
                 y = comparison,
                 color = component.label)) +
      geom_vline(xintercept = 0.5, color = "gray", linetype = 2)

    if (show.sd == TRUE & !all(is.na(tb$AUC.sd))) {
      auroc.plot =
        auroc.plot +
        geom_linerange(aes(xmin = AUC - AUC.sd, xmax = AUC + AUC.sd),
                       linewidth = 0.4,
                       position = position_dodge(width = 0.5))
    }

    auroc.plot =
      auroc.plot +
      geom_point(size = 2.5, position = position_dodge(width = 0.5)) +
      scale_x_continuous(limits = c(0, 1)) +
      scale_color_manual(values = component.colors, name = NULL) +
      xlab("Area under the ROC curve") +
      ylab(NULL) +
      ggtitle(label = title,
              subtitle = "*dashed gray line: value of a random ranking*") +
      theme_classic() +
      theme(axis.line.y = element_blank(),
            axis.ticks.y = element_blank(),
            axis.text = element_text(color = "black"),
            panel.grid.major.x = element_line(color = "gray", linewidth = 0.1),
            plot.title = ggtext::element_markdown(hjust = 0.5),
            plot.subtitle = ggtext::element_markdown(hjust = 0.5, size = 8))

    return(auroc.plot)
  } # END function
